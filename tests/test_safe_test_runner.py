"""Behavioural tests for ``scripts/safe-test.sh`` and ``tests/_run.py``.

Every nested invocation gets its own ``SAFE_TEST_LOCK`` (the outer run already
holds ``/tmp/carving-sim-test.lock``) and a fixture cgroup / ``MemAvailable``
so the assertions are deterministic on any host.
"""

from __future__ import annotations

import fcntl
import os
import re
import subprocess
import tempfile
import time
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNNER = ROOT / "scripts" / "safe-test.sh"
PROBE_MODULE = "_safe_test_probe"

PROBE_SOURCE = '''"""Generated by tests/test_safe_test_runner.py; safe to delete."""
import os
import time
import unittest


class Probe(unittest.TestCase):
    def test_probe(self):
        log = os.environ.get("SAFE_TEST_PROBE_LOG")
        with open(log, "a", encoding="utf-8") as stream:
            stream.write(f"{os.getpid()} start {time.time()}\\n")
        time.sleep(float(os.environ.get("SAFE_TEST_PROBE_SLEEP", "0")))
        allocate = int(os.environ.get("SAFE_TEST_PROBE_ALLOC_MB", "0"))
        if allocate:
            self.blob = bytearray(allocate * 1024 * 1024)
        with open(log, "a", encoding="utf-8") as stream:
            stream.write(f"{os.getpid()} end {time.time()}\\n")
'''

SUMMARY_RE = re.compile(
    r"safe-test: status=\d+ peak_rss_mb=\d+ wall_s=\d+ tier=(?:default|heavy)"
)


class RunnerTest(unittest.TestCase):
    def setUp(self):
        self.tempdir = tempfile.TemporaryDirectory()
        self.addCleanup(self.tempdir.cleanup)
        self.dir = Path(self.tempdir.name)
        self.lock = self.dir / "test.lock"
        self.probe_log = self.dir / "probe.log"
        self.probe_path = ROOT / "tests" / f"{PROBE_MODULE}.py"
        self.probe_path.write_text(PROBE_SOURCE, encoding="utf-8")
        self.addCleanup(lambda: self.probe_path.unlink(missing_ok=True))
        self.empty_cgroup = self.dir / "cgroup-empty"
        self.empty_cgroup.mkdir()
        self.meminfo = self.write_meminfo(65536)

    # -- fixtures ----------------------------------------------------------
    def write_meminfo(self, available_mb: int) -> Path:
        path = self.dir / "meminfo"
        path.write_text(
            f"MemTotal:       16777216 kB\n"
            f"MemAvailable:   {available_mb * 1024} kB\n",
            encoding="utf-8",
        )
        return path

    def write_cgroup_v1(self, limit_gib: int, usage_gib: int, inactive_gib: int) -> Path:
        root = self.dir / "cgroup-v1"
        memory = root / "memory"
        memory.mkdir(parents=True)
        (memory / "memory.limit_in_bytes").write_text(
            str(limit_gib * 1024**3), encoding="utf-8"
        )
        (memory / "memory.usage_in_bytes").write_text(
            str(usage_gib * 1024**3), encoding="utf-8"
        )
        (memory / "memory.stat").write_text(
            f"cache 0\n"
            f"total_inactive_file {inactive_gib * 1024**3}\n",
            encoding="utf-8",
        )
        return root

    def write_cgroup_v2(
        self, limit: str, usage_gib: int, inactive_gib: int
    ) -> Path:
        root = self.dir / "cgroup-v2"
        root.mkdir(parents=True)
        (root / "memory.max").write_text(limit, encoding="utf-8")
        (root / "memory.current").write_text(
            str(usage_gib * 1024**3), encoding="utf-8"
        )
        (root / "memory.stat").write_text(
            f"anon 0\ninactive_file {inactive_gib * 1024**3}\n", encoding="utf-8"
        )
        return root

    def env(self, **overrides: str) -> dict[str, str]:
        env = os.environ.copy()
        env.pop("RUN_HEAVY_TESTS", None)
        env.pop("NODE_OPTIONS", None)
        # Nested runs must use the documented default cap/budget, not whatever
        # the outer (possibly heavy) run was started with.
        env.pop("SAFE_TEST_AS_KB", None)
        env.pop("SAFE_TEST_BUDGET_MB", None)
        env.update(
            {
                "SAFE_TEST_LOCK": str(self.lock),
                "SAFE_TEST_MIN_AVAIL_MB": "0",
                "SAFE_TEST_CGROUP_ROOT": str(self.empty_cgroup),
                "SAFE_TEST_MEMINFO": str(self.meminfo),
                "SAFE_TEST_PROBE_LOG": str(self.probe_log),
            }
        )
        env.update(overrides)
        return env

    def run_runner(
        self, *args: str, env: dict[str, str] | None = None, timeout: int = 180
    ) -> subprocess.CompletedProcess:
        self.assertTrue(RUNNER.exists(), f"{RUNNER} does not exist")
        return subprocess.run(
            [str(RUNNER), *args],
            cwd=ROOT,
            env=env or self.env(),
            capture_output=True,
            text=True,
            timeout=timeout,
        )

    @staticmethod
    def output(process: subprocess.CompletedProcess) -> str:
        return f"{process.stdout}\n{process.stderr}"

    def intervals(self) -> dict[int, tuple[float, float]]:
        starts: dict[int, float] = {}
        ends: dict[int, float] = {}
        for line in self.probe_log.read_text(encoding="utf-8").splitlines():
            pid, kind, stamp = line.split()
            if kind == "start":
                starts[int(pid)] = float(stamp)
            else:
                ends[int(pid)] = float(stamp)
        return {pid: (start, ends[pid]) for pid, start in starts.items()}

    # -- lock --------------------------------------------------------------
    def test_concurrent_runs_queue_and_do_not_overlap(self):
        env = self.env(SAFE_TEST_PROBE_SLEEP="1.5")
        first = subprocess.Popen(
            [str(RUNNER), f"tests/{PROBE_MODULE}.py"],
            cwd=ROOT,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        try:
            time.sleep(0.4)
            second = subprocess.Popen(
                [str(RUNNER), f"tests/{PROBE_MODULE}.py"],
                cwd=ROOT,
                env=env,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
            )
            out1, err1 = first.communicate(timeout=180)
            out2, err2 = second.communicate(timeout=180)
        finally:
            for process in (first, locals().get("second")):
                if process is not None and process.poll() is None:
                    process.kill()

        self.assertEqual(first.returncode, 0, err1)
        self.assertEqual(second.returncode, 0, err2)
        self.assertIn(f"waiting for {self.lock}", f"{out2}\n{err2}")
        runs = sorted(self.intervals().values())
        self.assertEqual(len(runs), 2)
        self.assertGreaterEqual(runs[1][0], runs[0][1] - 0.05, runs)

    def test_lock_wait_timeout_exits_75(self):
        handle = self.lock.open("w", encoding="utf-8")
        try:
            fcntl.flock(handle, fcntl.LOCK_EX)
            started = time.monotonic()
            process = self.run_runner(
                f"tests/{PROBE_MODULE}.py",
                env=self.env(SAFE_TEST_LOCK_WAIT_S="1"),
                timeout=30,
            )
            elapsed = time.monotonic() - started
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)
            handle.close()

        self.assertEqual(process.returncode, 75, self.output(process))
        self.assertLess(elapsed, 15.0)
        self.assertFalse(self.probe_log.exists(), "no test may run without the lock")

    # -- available memory --------------------------------------------------
    def test_cgroup_v1_subtracts_reclaimable_page_cache(self):
        process = self.run_runner(
            f"tests/{PROBE_MODULE}.py",
            env=self.env(SAFE_TEST_CGROUP_ROOT=str(self.write_cgroup_v1(12, 9, 6))),
        )
        self.assertEqual(process.returncode, 0, self.output(process))
        self.assertIn("available_mb=9216", self.output(process))

    def test_cgroup_v2_subtracts_reclaimable_page_cache(self):
        process = self.run_runner(
            f"tests/{PROBE_MODULE}.py",
            env=self.env(
                SAFE_TEST_CGROUP_ROOT=str(self.write_cgroup_v2("12884901888", 9, 6))
            ),
        )
        self.assertEqual(process.returncode, 0, self.output(process))
        self.assertIn("available_mb=9216", self.output(process))

    def test_cgroup_v2_max_falls_back_to_mem_available(self):
        process = self.run_runner(
            f"tests/{PROBE_MODULE}.py",
            env=self.env(
                SAFE_TEST_CGROUP_ROOT=str(self.write_cgroup_v2("max", 9, 0)),
                SAFE_TEST_MEMINFO=str(self.write_meminfo(7000)),
            ),
        )
        self.assertEqual(process.returncode, 0, self.output(process))
        self.assertIn("available_mb=7000", self.output(process))

    def test_low_memory_refuses_and_releases_the_lock(self):
        low = self.env(
            SAFE_TEST_CGROUP_ROOT=str(self.write_cgroup_v1(1, 1, 0)),
            SAFE_TEST_MIN_AVAIL_MB="4608",
        )
        process = self.run_runner(f"tests/{PROBE_MODULE}.py", env=low)
        self.assertEqual(process.returncode, 75, self.output(process))
        self.assertIn("4608", self.output(process))
        self.assertFalse(self.probe_log.exists(), "no tests may run below the floor")

        followup = self.run_runner(
            f"tests/{PROBE_MODULE}.py", env=self.env(), timeout=60
        )
        self.assertEqual(followup.returncode, 0, self.output(followup))
        self.assertTrue(self.probe_log.exists(), "the lock was not released")

    # -- target conversion -------------------------------------------------
    def test_python_file_targets_become_module_names(self):
        process = self.run_runner("tests/test_tool_model.py", timeout=180)
        self.assertEqual(process.returncode, 0, self.output(process))
        text = self.output(process)
        self.assertRegex(text, r"test_tool_model\.")
        self.assertNotIn("test_carver_sim", text)

    def test_dotted_targets_pass_through(self):
        process = self.run_runner(f"{PROBE_MODULE}.Probe.test_probe")
        self.assertEqual(process.returncode, 0, self.output(process))
        self.assertIn("Ran 1 test", self.output(process))

    # -- containment -------------------------------------------------------
    def test_runaway_allocation_fails_with_memory_error(self):
        process = self.run_runner(
            f"tests/{PROBE_MODULE}.py",
            env=self.env(SAFE_TEST_PROBE_ALLOC_MB="6144"),
            timeout=120,
        )
        self.assertNotEqual(process.returncode, 0, self.output(process))
        self.assertIn("MemoryError", self.output(process))

    def test_budget_overrun_exits_4(self):
        process = self.run_runner(
            f"tests/{PROBE_MODULE}.py", env=self.env(SAFE_TEST_BUDGET_MB="1")
        )
        self.assertEqual(process.returncode, 4, self.output(process))
        self.assertIn("BUDGET EXCEEDED", self.output(process))

    def test_summary_line_format(self):
        process = self.run_runner(f"tests/{PROBE_MODULE}.py")
        self.assertEqual(process.returncode, 0, self.output(process))
        self.assertRegex(self.output(process), SUMMARY_RE.pattern)
        self.assertIn("tier=default", self.output(process))

    def test_node_mode_skips_the_address_space_cap(self):
        bindir = self.dir / "bin"
        bindir.mkdir()
        npm = bindir / "npm"
        npm.write_text(
            "#!/usr/bin/env bash\n"
            'echo "node-ulimit=$(ulimit -v)"\n'
            'echo "node-options=${NODE_OPTIONS:-}"\n',
            encoding="utf-8",
        )
        npm.chmod(0o755)
        process = self.run_runner(
            "--node",
            env=self.env(PATH=f"{bindir}{os.pathsep}{os.environ['PATH']}"),
        )
        self.assertEqual(process.returncode, 0, self.output(process))
        text = self.output(process)
        self.assertIn("node-ulimit=unlimited", text)
        self.assertIn("node-options=--max-old-space-size=2048", text)
        self.assertRegex(text, SUMMARY_RE.pattern)


if __name__ == "__main__":
    unittest.main()
